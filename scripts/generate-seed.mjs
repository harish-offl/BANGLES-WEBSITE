// Generates supabase/seed.sql from the audited catalogue copy.
//
//   node scripts/generate-seed.mjs
//
// The catalogue ids are deterministic UUIDv5 values minted by
// scripts/generate-catalog.mjs, so re-running this generator is safe and the
// produced seed upserts rather than duplicating rows.
//
// Store settings below mirror DEFAULT_SETTINGS in src/lib/site.ts. They are
// inlined here so the seed generator stays dependency-free (no TS toolchain).

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const catalogPath = path.join(root, "src", "lib", "data", "catalog.json");
const outPath = path.join(root, "supabase", "seed.sql");

const SETTINGS = {
  store_name: "Bangles by Beauty",
  whatsapp_number: "916381137076",
  contact_email: null,
  currency: "INR",
  announcement:
    "Free delivery on orders above \u20b92499 \u00b7 Handcrafted with love from Pattukottai",
  shipping_info:
    "Made to order with a processing time of 5 to 7 days. Free delivery on orders above \u20b92499.",
  footer_note: "Handcrafted with love from Pattukottai.",
  facebook_url: "https://www.facebook.com/share/1Csucpqcd4/",
  instagram_url: "https://www.instagram.com/bangles_by_beauty?igsh=MnJienJqMWludTNz",
  youtube_url: "https://youtube.com/%40bangles_by_beauty?si=WI2bStYuMaPkxQxy",
  pinterest_url: null,
  location: "Pattukottai",
  seo_title_template: "%s \u00b7 Bangles by Beauty",
  seo_default_description:
    "Handcrafted bangles, bridal sets and traditional jewellery from Pattukottai. Shop border bangles, bridal bangles, kundan hair bands and more.",
  free_shipping_threshold: 2499,
};

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlJson(value) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlArray(values) {
  if (!values || values.length === 0) return "'{}'::text[]";
  return `array[${values.map((v) => sqlString(v)).join(", ")}]`;
}

async function main() {
  const raw = await readFile(catalogPath, "utf8");
  const catalog = JSON.parse(raw);

  const lines = [];
  lines.push("-- seed.sql");
  lines.push("-- Generated by scripts/generate-seed.mjs — do not edit by hand.");
  lines.push(`-- Source: src/lib/data/catalog.json (${catalog.products.length} products, ${catalog.categories.length} categories).`);
  lines.push("-- Idempotent: every statement upserts on the primary key.");
  lines.push("");
  lines.push("begin;");
  lines.push("");

  // Store settings -----------------------------------------------------------
  lines.push("-- Storefront settings (mirror DEFAULT_SETTINGS in src/lib/site.ts)");
  const settingRows = Object.entries(SETTINGS).map(
    ([key, value]) => `  (${sqlString(key)}, ${sqlJson(value)})`,
  );
  lines.push("insert into public.store_settings (key, value) values");
  lines.push(settingRows.join(",\n"));
  lines.push("on conflict (key) do update set value = excluded.value, updated_at = timezone('utc', now());");
  lines.push("");

  // Categories ---------------------------------------------------------------
  lines.push("-- Categories");
  lines.push(
    "insert into public.categories (id, name, slug, description, image_url, sort_order, is_active) values",
  );
  const catRows = catalog.categories.map((c) =>
    `  (${sqlString(c.id)}, ${sqlString(c.name)}, ${sqlString(c.slug)}, ${sqlString(
      c.description ?? null,
    )}, ${sqlString(c.image_url ?? null)}, ${Number(c.sort_order ?? 0)}, ${c.is_active ? "true" : "false"})`,
  );
  lines.push(catRows.join(",\n"));
  lines.push(
    "on conflict (id) do update set name = excluded.name, slug = excluded.slug, description = excluded.description, image_url = excluded.image_url, sort_order = excluded.sort_order, is_active = excluded.is_active, updated_at = timezone('utc', now());",
  );
  lines.push("");

  // Products -----------------------------------------------------------------
  lines.push("-- Products");
  const productColumns =
    "id, category_id, name, slug, description, sku, price, compare_at_price, stock_quantity, primary_image_url, colours, colour_images, is_active, is_featured, is_new_arrival, seo_title, seo_description, legacy_id, legacy_image_source, sort_index";
  lines.push(`insert into public.products (${productColumns}) values`);
  const prodRows = catalog.products.map((p) =>
    `  (${sqlString(p.id)}, ${sqlString(p.category_id ?? null)}, ${sqlString(p.name)}, ${sqlString(
      p.slug,
    )}, ${sqlString(p.description ?? "")}, ${sqlString(p.sku ?? null)}, ${Number(p.price ?? 0)}, ${
      p.compare_at_price === null || p.compare_at_price === undefined
        ? "null"
        : Number(p.compare_at_price)
    }, ${
      p.stock_quantity === null || p.stock_quantity === undefined ? "null" : Number(p.stock_quantity)
    }, ${sqlString(p.primary_image_url ?? null)}, ${sqlArray(p.colours)}, ${sqlJson(
      Array.isArray(p.colour_images) ? p.colour_images : [],
    )}, ${p.is_active === false ? "false" : "true"
    }, ${p.is_featured ? "true" : "false"}, ${p.is_new_arrival ? "true" : "false"}, ${sqlString(
      p.seo_title ?? null,
    )}, ${sqlString(p.seo_description ?? null)}, ${sqlString(p.legacy_id ?? null)}, ${sqlString(
      p.legacy_image_source ?? null,
    )}, ${Number(p.sort_index ?? 0)})`,
  );
  lines.push(prodRows.join(",\n"));
  lines.push(
    "on conflict (id) do update set category_id = excluded.category_id, name = excluded.name, slug = excluded.slug, description = excluded.description, sku = excluded.sku, price = excluded.price, compare_at_price = excluded.compare_at_price, stock_quantity = excluded.stock_quantity, primary_image_url = excluded.primary_image_url, colours = excluded.colours, colour_images = excluded.colour_images, is_active = excluded.is_active, is_featured = excluded.is_featured, is_new_arrival = excluded.is_new_arrival, seo_title = excluded.seo_title, seo_description = excluded.seo_description, legacy_id = excluded.legacy_id, legacy_image_source = excluded.legacy_image_source, sort_index = excluded.sort_index, updated_at = timezone('utc', now());",
  );
  lines.push("");
  lines.push("commit;");
  lines.push("");

  await writeFile(outPath, lines.join("\n"), "utf8");
  console.log(
    `Wrote ${path.relative(root, outPath)} with ${catalog.categories.length} categories and ${catalog.products.length} products.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
