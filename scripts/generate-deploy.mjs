// Regenerates supabase/deploy.sql by concatenating every migration in order,
// followed by the generated seed file. Keeps the single-file Supabase deploy
// script in sync with supabase/migrations so it never drifts again.
//
// Usage: node scripts/generate-deploy.mjs

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");
const seedPath = join(root, "supabase", "seed.sql");
const outPath = join(root, "supabase", "deploy.sql");

const header = `-- Bangles by Beauty - single-file Supabase deploy script.
--
-- Generated by scripts/generate-deploy.mjs - do not edit by hand.
-- Concatenates supabase/migrations/*.sql in order, then supabase/seed.sql.
--
-- Run this once in the Supabase SQL editor (or psql) to provision the schema,
-- security policies and seed catalogue data. Every statement is idempotent, so
-- re-running it is safe.
`;

const migrationFiles = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = [];
for (const file of migrationFiles) {
  const sql = readFileSync(join(migrationsDir, file), "utf8").trimEnd();
  parts.push(sql);
}

const seed = readFileSync(seedPath, "utf8").trimEnd();
parts.push(seed);

const output = `${header}\n${parts.join("\n\n")}\n`;
writeFileSync(outPath, output, "utf8");

console.log(
  `Wrote ${outPath} (${migrationFiles.length} migrations + seed.sql, ${output.length} bytes)`,
);
